<script>
(function(){
 const root=document.querySelector('[data-sb-about]');
 if(!root)return;
 const card=root.querySelector('[data-sb-about-card]');
 const bg=root.querySelector('[data-sb-about-bg]');
 window.addEventListener('load',()=>{requestAnimationFrame(()=>{if(!card)return;card.style.opacity='1';card.style.transform='translateY(0)';});});
 let lastY=0;function onScroll(){if(!bg)return;const y=window.scrollY||window.pageYOffset;if(Math.abs(y-lastY)<2)return;lastY=y;const offset=Math.min(40,y*0.06);bg.style.transform=`translateY(${offset}px) scale(1.03)`;}
 document.addEventListener('scroll',onScroll,{passive:true});
 const counters=root.querySelectorAll('[data-sb-count]');let counted=false;const io=new IntersectionObserver(entries=>{if(!counted&&entries.some(e=>e.isIntersecting)){counted=true;counters.forEach(el=>{const to=parseInt(el.getAttribute('data-sb-count'),10)||0;const isPercent=(el.textContent.trim().endsWith('%'));animateNumber(el,to,900,isPercent);});}}, {threshold:0.35});
 io.observe(root);
 function animateNumber(el,to,duration,isPercent){const start=0,t0=performance.now();function tick(t){const p=Math.min(1,(t-t0)/duration);const eased=(p<0.5)?2*p*p:-1+(4-2*p)*p;const val=Math.floor(start+(to-start)*eased);el.textContent=isPercent?(val+'%'):new Intl.NumberFormat('vi-VN').format(val)+(to>=1000?'+':'');if(p<1)requestAnimationFrame(tick);}requestAnimationFrame(tick);}
})();
</script>
